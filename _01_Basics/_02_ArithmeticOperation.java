package _01_Basics;

public class _02_ArithmeticOperation {

	public static void main(String[] args) {
		int x= 5;
		int y= 2;
		System.out.println(x+y);
		System.out.println(x-y);
		System.out.println(x*y);
		System.out.println(x/y);
		// Using float
		System.out.println((float)x*y);
		System.out.println((float)x/y);
	}

}
