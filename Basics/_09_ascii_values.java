package Github.JAVA_DSA_Practice.Basics;

import java.util.Scanner;

public class _09_ascii_values {
    public static void main(String[] args) {
        Scanner sc= new Scanner(System.in);
        char ch;
        ch='A';
        System.out.println("The ASCII value of A is: "+(int)ch);
        ch='Z';
        System.out.println("The ASCII value of Z is: "+(int)ch);
        ch='a';
        System.out.println("The ASCII value of a is: "+(int)ch);
        ch='b';
        System.out.println("The ASCII value of b is: "+(int)ch);
        ch='1';
        System.out.println("The ASCII value of 1 is: "+(int)ch);
        ch='9';
        System.out.println("The ASCII value of 9 is: "+(int)ch);
    }
}
